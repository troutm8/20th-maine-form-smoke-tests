import { test, expect } from '@playwright/test';
import AxeBuilder from '@axe-core/playwright';
import { EnlistmentForm } from './enlistment-form';

// Page-level smoke checks. None of these submit the form.

test.describe('Enlistment page loads with the expected form', () => {
  let form: EnlistmentForm;

  test.beforeEach(async ({ page }) => {
    form = new EnlistmentForm(page);
    await form.goto();
  });

  test('page title', async ({ page }) => {
    await expect(page).toHaveTitle(/Enlistment Application/);
  });

  test('every field is present and enabled', async () => {
    const fields = [
      form.firstName, form.lastName, form.country, form.address, form.city, form.zip,
      form.cellPhone, form.homePhone, form.email,
      form.membershipFamily, form.membershipStudent, form.payOnline, form.payCheck,
      form.agreement, form.signature, form.date,
    ];
    for (let n = 1; n <= 7; n++) fields.push(form.familyName(n), form.familyAge(n));

    for (const field of fields) {
      await expect(field).toBeAttached();
      await expect(field).toBeEnabled();
    }
    await expect(form.submit).toBeVisible();
  });

  test('required text fields are marked required', async () => {
    for (const field of [form.firstName, form.lastName, form.address, form.city, form.zip,
      form.cellPhone, form.email, form.agreement, form.signature]) {
      await expect(field).toHaveAttribute('required', '');
    }
  });

  test('optional fields are not marked required', async () => {
    await expect(form.homePhone).not.toHaveAttribute('required', '');
    for (let n = 1; n <= 7; n++) {
      await expect(form.familyName(n)).not.toHaveAttribute('required', '');
      await expect(form.familyAge(n)).not.toHaveAttribute('required', '');
    }
  });

  test('membership prices are correct', async () => {
    await expect(form.membershipFamily).toBeAttached();
    await expect(form.membershipStudent).toBeAttached();
    await expect(form.form).toContainText('Individual or Family - $45');
    await expect(form.form).toContainText('Single Student - $20');
  });

  test('check-mailing instructions are correct', async () => {
    await expect(form.form).toContainText('Make checks payable to 20th Maine Co. G');
    await expect(form.form).toContainText('Cpl. Dave Bolland, 4525 Hazelwood Ave., Sacramento, CA 95821');
  });

  test('enlistment agreement text is intact', async () => {
    // Catches accidental edits to the legal wording.
    for (const phrase of [
      'I hereby apply to enlist in the service of the Army of the United States with the 20th Maine Volunteer Infantry, Company G for one year.',
      'I hereby agree to follow all lawful orders of the elected company commander, commissioned officers and noncommissioned officers.',
      'American Civil War Association (ACWA) bylaws and policies',
      "Family members' ages and payment details are seen only by the officers.",
    ]) {
      await expect(form.form).toContainText(phrase);
    }
  });

  // Report-only: much of the markup is generated by Wix and not fixable by us,
  // so findings are attached to the HTML report instead of failing the run.
  test('accessibility scan (report only)', async ({ page }, testInfo) => {
    const results = await new AxeBuilder({ page }).include('form').analyze();
    const serious = results.violations.filter(v => v.impact === 'critical' || v.impact === 'serious');
    const summary = serious.map(v => `${v.id}: ${v.help} (${v.nodes.length} element(s))`);
    testInfo.annotations.push({ type: 'a11y', description: summary.join('; ') || 'no serious issues' });
    await testInfo.attach('axe-results.json', { body: JSON.stringify(results.violations, null, 2), contentType: 'application/json' });
  });
});
